/**
 * 返回 data 中所有包含 keyword 的元素下标。
 * 在 100K 行、关键词 5 字符时比纯 JS 快约 3 倍。
 */
export async function filterIndices(
  data: string[],
  keyword: string,
  caseSensitive = false
): Promise<number[]> {
  const m = await getModule()
  return m.filterIndices(data, keyword, caseSensitive)
}

