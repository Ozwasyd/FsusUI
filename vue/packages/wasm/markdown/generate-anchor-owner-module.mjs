import assert from 'node:assert/strict'
import { readFile, writeFile } from 'node:fs/promises'

const [wasmPath, translatedPath, outputPath, ...extra] = process.argv.slice(2)
if (!wasmPath || !translatedPath || !outputPath || extra.length > 0) {
  throw new Error('Expected the owner WASM, wasm2js module, and output paths')
}

const module = new globalThis.WebAssembly.Module(await readFile(wasmPath))
const imports = globalThis.WebAssembly.Module.imports(module)
  .map(({ module, name, kind }) => `${module}.${name}:${kind}`)
  .sort()
assert.deepEqual(imports, [
  'env.emscripten_notify_memory_growth:function',
  'wasi_snapshot_preview1.fd_close:function',
  'wasi_snapshot_preview1.fd_seek:function',
  'wasi_snapshot_preview1.fd_write:function',
])
const exports = globalThis.WebAssembly.Module.exports(module)
  .map(({ name, kind }) => `${name}:${kind}`)
  .sort()
assert.deepEqual(exports, [
  '__indirect_function_table:table',
  '_emscripten_stack_restore:function',
  '_initialize:function',
  'emscripten_stack_get_current:function',
  'fa_alloc:function',
  'fa_collect:function',
  'fa_data:function',
  'fa_free:function',
  'memory:memory',
])

const translated = await readFile(translatedPath, 'utf8')
const prefix =
  "import * as env from 'env';\nimport * as wasi_snapshot_preview1 from 'wasi_snapshot_preview1';\n\n"
const trailer = `var retasmFunc = asmFunc({
  "env": env,
  "wasi_snapshot_preview1": wasi_snapshot_preview1,
});
${[
  'memory',
  'fa_alloc',
  'fa_free',
  'fa_data',
  'fa_collect',
  '_initialize',
  '_emscripten_stack_restore',
  'emscripten_stack_get_current',
]
  .map((name) => `export var ${name} = retasmFunc.${name};`)
  .join('\n')}
`
assert.ok(translated.startsWith(`${prefix}function Table(`))
assert.ok(translated.endsWith(trailer))
const body = translated
  .slice(prefix.length, -trailer.length)
  .replace(/[ \t]+$/gmu, '')
  .trimEnd()
assert.match(body, /^function asmFunc\(imports\) \{/mu)
assert.doesNotMatch(
  body,
  /^\s*(?:import|export)\b|\b(?:eval|Function|WebAssembly)\s*(?:[.(]|$)/mu,
)

// Only expose the private factory. The consumer injects the allowlisted
// no-op shims and lazily initializes its own memory on first use.
const source = `// Generated by markdown/build-anchor-owner.sh. Do not edit manually.
${body}

export { asmFunc as createOwnerAbi }
`
await writeFile(outputPath, source)
