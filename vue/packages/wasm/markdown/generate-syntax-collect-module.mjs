import { readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const markdownDirectory = dirname(fileURLToPath(import.meta.url))
const wasmPath = resolve(markdownDirectory, 'syntax-collect.wasm')
const outputPath = resolve(markdownDirectory, 'syntax-collect.generated.ts')
const wasmBase64 = (await readFile(wasmPath)).toString('base64')
const source = `// Generated by markdown/generate-syntax-collect-module.mjs. Do not edit manually.
// The embedded bytes keep the synchronous parser-owned projection available in browsers and Workers.
export const markdownSyntaxCollectWasmBase64 = '${wasmBase64}'
`

await writeFile(outputPath, source)
